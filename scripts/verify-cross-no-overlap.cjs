'use strict';
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const cwd = path.join(__dirname, '..');
const result = spawnSync(process.execPath, ['scripts/local-cross.cjs'], { cwd, env: { ...process.env, CROSS_VERIFY_NO_OVERLAP: '1' }, encoding: 'utf8', timeout: 180000 });
assert.equal(result.status, 1, 'No-overlap runner must exit nonzero');
const match = result.stdout.match(/Cross summary: (.+\/case-summary\.json)/);
assert.ok(match, 'Persistent summary is missing');
const summary = JSON.parse(fs.readFileSync(match[1]));
assert.equal(summary.runnerStatus, 'failed'); assert.equal(summary.overlap, 'unconfirmed');
assert.deepEqual(summary.failureKinds, ['overlap-unconfirmed']);
assert.equal(summary.ui, 'PASS'); assert.equal(summary.batch, 'completed'); assert.equal(summary.finalComparison, 'PASS');
assert.equal(summary.finalUi.text, '親データ: 15000件');
assert.equal(summary.cleanup, 'completed'); assert.equal(summary.environmentCleanup, 'completed'); assert.equal(summary.batchStopped, true);
assert.equal(summary.attempts.length, 1); assert(summary.attempts[0].operation.end < summary.batchStart);
console.log(`No-overlap: explicit unconfirmed, runner failure and cleanup confirmed: ${summary.runId}`);
